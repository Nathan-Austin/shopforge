#!/usr/bin/env python3
"""Reads the product field catalogue and drives the generator's field picker.

Usage:
  fieldpicker.py menu <catalogue.ts> <mode>
  fieldpicker.py resolve <catalogue.ts> <mode> <selection>
  fieldpicker.py config <catalogue.ts> <mode> <keys-csv> <heat-json> <out.ts>
"""
import json
import re
import sys


def parse_catalogue(path, mode):
    text = open(path, encoding='utf-8').read()
    start = text.index('export const PRODUCT_FIELDS')
    end = text.index('\n];', start)
    body = text[start:end]

    fields = []
    for block in re.findall(r'\{\s*\n(.*?)\n  \}', body, re.S):
        def grab(name):
            m = re.search(rf"^\s*{name}: '([^']*)'", block, re.M)
            return m.group(1) if m else None

        key = grab('key')
        if not key:
            continue
        modes = re.search(r"^\s*modes: \[([^\]]*)\]", block, re.M)
        modes = [m.strip().strip("'") for m in modes.group(1).split(',') if m.strip()] if modes else []
        fields.append({
            'key': key,
            'label': grab('label') or key,
            'group': grab('group') or 'other',
            'modes': modes,
            'recommended': bool(re.search(r'^\s*recommended: true', block, re.M)),
        })

    if len(fields) < 20:
        raise SystemExit(f'Only parsed {len(fields)} product fields from {path}; catalogue format changed?')

    return [f for f in fields if not f['modes'] or mode in f['modes']]


def group_labels(path):
    text = open(path, encoding='utf-8').read()
    start = text.index('export const PRODUCT_FIELD_GROUPS')
    end = text.index('\n];', start)
    return dict(re.findall(r"key: '([^']+)', label: '([^']+)'", text[start:end]))


def menu(path, mode):
    fields = parse_catalogue(path, mode)
    labels = group_labels(path)
    out = ["", "Which product fields should the admin panel manage?", ""]
    out.append("   0) ALL fields")
    current = None
    for index, field in enumerate(fields, start=1):
        if field['group'] != current:
            current = field['group']
            out.append(f"  --- {labels.get(current, current)}")
        star = ' *' if field['recommended'] else ''
        out.append(f"  {index:2d}) {field['label']}{star}")
    out += [
        "",
        "  * = in the recommended set.",
        "  Enter 0 for all, numbers like 1,3,7, or press Enter for the recommended set.",
    ]
    print("\n".join(out))


def resolve(path, mode, selection):
    fields = parse_catalogue(path, mode)
    selection = (selection or '').strip().lower()

    if selection in ('', 'recommended', 'default'):
        keys = [f['key'] for f in fields if f['recommended']]
    elif selection in ('0', 'all'):
        keys = [f['key'] for f in fields]
    else:
        wanted = [part.strip() for part in selection.split(',') if part.strip()]
        if '0' in wanted or 'all' in wanted:
            keys = [f['key'] for f in fields]
        else:
            by_key = {f['key']: f for f in fields}
            keys = []
            for part in wanted:
                if part.isdigit():
                    index = int(part) - 1
                    if 0 <= index < len(fields):
                        keys.append(fields[index]['key'])
                elif part in by_key:
                    keys.append(part)
            if not keys:
                keys = [f['key'] for f in fields if f['recommended']]

    ordered = [f['key'] for f in fields if f['key'] in set(keys)]
    print(','.join(ordered))


def config(path, mode, keys_csv, heat_json, out_path):
    fields = parse_catalogue(path, mode)
    valid = {f['key'] for f in fields}
    keys = [k for k in (part.strip() for part in keys_csv.split(',')) if k in valid]
    heat = json.loads(heat_json) if heat_json and heat_json != 'null' else None

    lines = [
        '/**',
        ' * Generated by create-next-commerce-template-ssr.sh.',
        ' *',
        ' * Which product fields this shop uses, and how it talks about heat.',
        ' * Every column exists in the database regardless, so switching a field',
        ' * on here is enough: no migration needed.',
        ' */',
        '',
        "import type { HeatScale } from './heat';",
        '',
        '/** Fields the admin form shows and the server actions save. */',
        'export const PRODUCT_FIELD_KEYS = [',
    ]
    for key in keys:
        lines.append(f"  '{key}',")
    lines += [
        '] as const;',
        '',
    ]

    if heat is None:
        lines += [
            '/** This store mode does not track heat. */',
            'export const HEAT_SCALE: HeatScale | null = null;',
            '',
        ]
    else:
        lines += [
            '/**',
            ' * Heat is stored as a number from 0 to `max`. The bands turn that',
            ' * number into a word; drop or rename them freely, and leave the list',
            ' * empty to show numbers only.',
            ' */',
            'export const HEAT_SCALE: HeatScale | null = {',
            f"  max: {heat['max']},",
            f"  display: '{heat['display']}',",
            '  bands: [',
        ]
        for band in heat['bands']:
            lines.append(f"    {{ word: '{band['word']}', upTo: {band['upTo']} }},")
        lines += ['  ],', '};', '']

    open(out_path, 'w', encoding='utf-8').write('\n'.join(lines))


if __name__ == '__main__':
    command = sys.argv[1]
    if command == 'menu':
        menu(sys.argv[2], sys.argv[3])
    elif command == 'resolve':
        resolve(sys.argv[2], sys.argv[3], sys.argv[4])
    elif command == 'config':
        config(sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5], sys.argv[6])
    else:
        raise SystemExit(f'Unknown command: {command}')
